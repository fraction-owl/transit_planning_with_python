#   OVERFLOW_ROUTING = {
#       "layover_bay_A": ["LAYOVER"],  # near space: medium layovers, and bumped buses
#       "layover_bay_B": ["LONG BREAK"],  # far space: long layovers only
#   }
#   BUMPED_TO_SPACE = "layover_bay_A"
OVERFLOW_ROUTING: Dict[str, List[str]] = {}
BUMPED_TO_SPACE: str = ""

