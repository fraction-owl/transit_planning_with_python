def _stop_occupancy(df_in: DataFrame) -> DataFrame:
    """Rows that occupy a stop (bay), with a numeric minute column."""
    occ = df_in[df_in["Status"].isin(bay_statuses()) & df_in["Stop ID"].notna()].copy()
    occ["Minute"] = occ["Timestamp"].apply(timestamp_to_minutes)
    return occ.dropna(subset=["Minute"])


def build_conflict_events(df_in: DataFrame) -> DataFrame:
    """Collapse per-minute stop conflicts into events.

    An event is a run of consecutive minutes at one stop during which more
    buses occupy it than its capacity. Buses named on the event are every bus
    present at that stop during the run.

    Args:
    ----------
    df_in :
        Timeline rows for one cluster (must include ``Stop ID``, ``Stop
        Name``, ``Timestamp``, ``Status``, ``Block``).

    Returns:
    -------
    pandas.DataFrame
        One row per event: stop, window, length, bus count, bus labels.
    """
    stop_caps = build_stop_capacities()
    occ = _stop_occupancy(df_in)
    events: List[Dict[str, Any]] = []

    for stop_id, stop_df in occ.groupby("Stop ID"):
        cap = stop_caps.get(str(stop_id), 1)
        per_minute = stop_df.groupby("Minute")
        conflict_minutes = sorted(m for m, g in per_minute if len(g) > cap)
        if not conflict_minutes:
            continue
        stop_name = stop_df["Stop Name"].iloc[0]

        run_start = conflict_minutes[0]
        run_prev = run_start
        for m in conflict_minutes[1:] + [None]:
            if m is not None and m == run_prev + 1:
                run_prev = m
                continue
            window = stop_df[(stop_df["Minute"] >= run_start) & (stop_df["Minute"] <= run_prev)]
            labels = sorted({bus_label(r) for _, r in window.iterrows()})
            events.append(
                {
                    "Stop ID": stop_id,
                    "Stop Name": stop_name,
                    "Start": window["Timestamp"].min(),
                    "End": window["Timestamp"].max(),
                    "Minutes": int(run_prev - run_start + 1),
                    "Peak Buses": int(window.groupby("Minute").size().max()),
                    "Buses": len(labels),
                    "Bus 1": labels[0] if len(labels) > 0 else "",
                    "Bus 2": labels[1] if len(labels) > 1 else "",
                    "Bus 3": labels[2] if len(labels) > 2 else "",
                    "Others": "; ".join(labels[3:]),
                }
            )
            if m is not None:
                run_start = run_prev = m

    cols = [
        "Stop ID",
        "Stop Name",
        "Start",
        "End",
        "Minutes",
        "Peak Buses",
        "Buses",
        "Bus 1",
        "Bus 2",
        "Bus 3",
        "Others",
    ]
    out = DataFrame(events, columns=cols)
    return out.sort_values(["Start", "Stop ID"]).reset_index(drop=True)


def _cluster_routing(cluster_info: Dict[str, List[str]]) -> Dict[str, str]:
    """``status -> overflow space`` for one cluster.

    Only the ``OVERFLOW_ROUTING`` entries whose space is one of this cluster's
    ``overflow_bays`` apply, so a routing written for one facility does not
    leak into another. Empty when routing is off or nothing matches.
    """
    overflow_bays = {str(b) for b in cluster_info.get("overflow_bays", [])}
    status_to_space: Dict[str, str] = {}
    for space, statuses in OVERFLOW_ROUTING.items():
        if str(space) in overflow_bays:
            for status in statuses:
                status_to_space[status] = str(space)
    return status_to_space


def _validate_overflow_routing() -> None:
    """Warn about routing settings that can never apply to any configured cluster."""
    all_overflow = {
        str(b) for cinfo in CLUSTER_DEFINITIONS.values() for b in cinfo.get("overflow_bays", [])
    }
    for space in OVERFLOW_ROUTING:
        if str(space) not in all_overflow:
            logging.warning(
                "OVERFLOW_ROUTING space '%s' is not an overflow bay of any cluster; ignored.", space
            )
    if BUMPED_TO_SPACE and BUMPED_TO_SPACE not in OVERFLOW_ROUTING:
        logging.warning(
            "BUMPED_TO_SPACE '%s' is not a key of OVERFLOW_ROUTING; bumped buses are "
            "charged to the overflow pool instead.",
            BUMPED_TO_SPACE,
        )


def _overflow_rows(df_in: DataFrame, cluster_info: Dict[str, List[str]]) -> DataFrame:
    """Rows spent on the overflow space, with ``Minute`` and the ``Space`` each bus is routed to.

    With no routing for this cluster every row gets ``Space = "(pool)"``.
    Statuses not listed in the routing fall to the first overflow bay.
    """
    rows = df_in[df_in["Status"].isin(OVERFLOW_STATUSES) & df_in["Stop ID"].notna()].copy()
    rows["Minute"] = rows["Timestamp"].apply(timestamp_to_minutes)
    rows = rows.dropna(subset=["Minute"])
    overflow_bays = [str(b) for b in cluster_info.get("overflow_bays", [])]
    status_to_space = _cluster_routing(cluster_info)
    if not status_to_space or not overflow_bays:
        rows["Space"] = "(pool)"
        return rows
    rows["Space"] = rows["Status"].map(status_to_space).fillna(overflow_bays[0])
    return rows


def build_overflow_events(df_in: DataFrame, cluster_info: Dict[str, List[str]]) -> DataFrame:
    """Runs of consecutive minutes where an overflow space holds more buses than it can.

    Each routed space holds one bus. With routing off, the pool's capacity is
    the number of overflow bays.
    """
    rows = _overflow_rows(df_in, cluster_info)
    n_overflow = len(cluster_info.get("overflow_bays", []))
    events: List[Dict[str, Any]] = []
    for space, space_df in rows.groupby("Space"):
        cap = n_overflow if space == "(pool)" else 1
        over = sorted(m for m, g in space_df.groupby("Minute") if len(g) > cap)
        if not over:
            continue
        run_start = run_prev = over[0]
        for m in over[1:] + [None]:
            if m is not None and m == run_prev + 1:
                run_prev = m
                continue
            window = space_df[(space_df["Minute"] >= run_start) & (space_df["Minute"] <= run_prev)]
            labels = sorted({bus_label(r) for _, r in window.iterrows()})
            events.append(
                {
                    "Space": space,
                    "Capacity": cap,
                    "Start": window["Timestamp"].min(),
                    "End": window["Timestamp"].max(),
                    "Minutes": int(run_prev - run_start + 1),
                    "Peak Buses": int(window.groupby("Minute").size().max()),
                    "Buses": len(labels),
                    "Bus 1": labels[0] if len(labels) > 0 else "",
                    "Bus 2": labels[1] if len(labels) > 1 else "",
                    "Bus 3": labels[2] if len(labels) > 2 else "",
                    "Others": "; ".join(labels[3:]),
                }
            )
            if m is not None:
                run_start = run_prev = m
    cols = [
        "Space",
        "Capacity",
        "Start",
        "End",
        "Minutes",
        "Peak Buses",
        "Buses",
        "Bus 1",
        "Bus 2",
        "Bus 3",
        "Others",
    ]
    return DataFrame(events, columns=cols).sort_values(["Start", "Space"]).reset_index(drop=True)


def build_minute_rules(df_in: DataFrame, cluster_info: Dict[str, List[str]]) -> Dict[str, Any]:
    """Count conflict minutes for one cluster under three rules.

    Rules
    -----
    ``any_stop``
        Minutes with at least one stop over capacity.
    ``two_or_more_stops``
        Minutes with two or more stops over capacity at once. This is the
        "a single-bay conflict is resolved by one bus using the layover
        space" rule, taken at face value (the space is assumed free).
    ``overflow_adjusted``
        Minutes where the excess buses across all stops, plus buses already
        on the overflow space (LAYOVER / LONG BREAK), exceed the number of
        overflow bays defined for the cluster. With ``OVERFLOW_ROUTING`` set,
        the excess is charged to ``BUMPED_TO_SPACE`` only and compared with
        that space's occupancy (capacity 1).

    Also returns per-space peak occupancy and over-capacity minutes under
    ``per_space``.
    """
    stop_caps = build_stop_capacities()
    n_overflow = len(cluster_info.get("overflow_bays", []))

    occ = _stop_occupancy(df_in)
    excess_by_minute: Dict[int, int] = {}
    stops_over_by_minute: Dict[int, int] = {}
    for (stop_id, minute), g in occ.groupby(["Stop ID", "Minute"]):
        over = len(g) - stop_caps.get(str(stop_id), 1)
        if over > 0:
            excess_by_minute[minute] = excess_by_minute.get(minute, 0) + over
            stops_over_by_minute[minute] = stops_over_by_minute.get(minute, 0) + 1

    on_overflow = _overflow_rows(df_in, cluster_info)
    overflow_by_minute = on_overflow.groupby("Minute").size().to_dict()

    per_space: Dict[str, Dict[str, int]] = {}
    for space, space_df in on_overflow.groupby("Space"):
        cap = n_overflow if space == "(pool)" else 1
        by_minute = space_df.groupby("Minute").size()
        per_space[str(space)] = {
            "capacity": cap,
            "peak": int(by_minute.max()) if len(by_minute) else 0,
            "minutes_over": int((by_minute > cap).sum()),
            "minutes_used": int(len(by_minute)),
        }

    routed_spaces = set(_cluster_routing(cluster_info).values())
    bumped_to = BUMPED_TO_SPACE if BUMPED_TO_SPACE in routed_spaces else ""
    if bumped_to:
        bump_df = on_overflow[on_overflow["Space"] == bumped_to]
        bump_by_minute = bump_df.groupby("Minute").size().to_dict()
        overflow_adjusted = sum(
            1 for m, ex in excess_by_minute.items() if ex + bump_by_minute.get(m, 0) > 1
        )
    else:
        overflow_adjusted = sum(
            1
            for m, ex in excess_by_minute.items()
            if ex + overflow_by_minute.get(m, 0) > n_overflow
        )

    return {
        "any_stop": len(excess_by_minute),
        "two_or_more_stops": sum(1 for n in stops_over_by_minute.values() if n >= 2),
        "overflow_adjusted": overflow_adjusted,
        "overflow_capacity": n_overflow,
        "peak_on_overflow": int(max(overflow_by_minute.values(), default=0)),
        "minutes_overflow_over_capacity": sum(
            1 for n in overflow_by_minute.values() if n > n_overflow
        ),
        "per_space": per_space,
        "bumped_to": bumped_to or "(pool)",
    }


def build_bay_tally(df_in: DataFrame, events: DataFrame) -> DataFrame:
    """Per-stop conflict minutes and events, one row per stop."""
    stop_caps = build_stop_capacities()
    occ = _stop_occupancy(df_in)
    rows: List[Dict[str, Any]] = []
    for stop_id, stop_df in occ.groupby("Stop ID"):
        cap = stop_caps.get(str(stop_id), 1)
        minutes = sum(1 for _, g in stop_df.groupby("Minute") if len(g) > cap)
        rows.append(
            {
                "Stop ID": stop_id,
                "Stop Name": stop_df["Stop Name"].iloc[0],
                "Capacity": cap,
                "Conflict Minutes": minutes,
                "Conflict Events": int((events["Stop ID"] == stop_id).sum())
                if not events.empty
                else 0,
            }
        )
    return DataFrame(
        rows, columns=["Stop ID", "Stop Name", "Capacity", "Conflict Minutes", "Conflict Events"]
    )


def _txt(value: object) -> str:
    """Cell value as text, with ``None``/NaN as an empty string."""
    return "" if value is None or pd.isna(value) else str(value)


def _layover_run_row(
    block: object,
    current: List[Dict[str, Any]],
    after_status: str,
    after_stop: str,
    trip_lookup: Dict[str, str],
    has_prev_next: bool,
    occupying: Set[str],
) -> Dict[str, Any]:
    """Summarize one layover run (consecutive cluster minutes of a block) as a row.

    Args:
        block: Block ID the run belongs to.
        current: The run's timeline rows in minute order (non-empty).
        after_status: Status of the row that ended the run (``"END"`` at the
            end of the block's day).
        after_stop: Stop ID of that row, if it has one.
        trip_lookup: ``trip_id -> "route headsign"`` labels.
        has_prev_next: Whether the timeline carries ``Prev Trip ID`` /
            ``Next Trip ID`` columns (Step 1 writes them).
        occupying: Statuses that count as in-bay (see :func:`bay_statuses`).

    Returns:
        One ``Layover Runs`` row.
    """
    statuses = [r["Status"] for r in current]
    in_bay = sum(1 for st in statuses if st in occupying or st == "DWELL")
    overflow = sum(1 for st in statuses if st in OVERFLOW_STATUSES)
    first, last = current[0], current[-1]
    prev_tid = _txt(first.get("Prev Trip ID")) if has_prev_next else ""
    next_tid = _txt(last.get("Next Trip ID")) if has_prev_next else ""
    if first["Status"] == "ARRIVE" and not prev_tid:
        prev_tid = _txt(first.get("Trip ID"))
    if last["Status"] == "LOADING" and not next_tid:
        next_tid = _txt(last.get("Trip ID"))
    if not prev_tid:
        run_type = "pull-out"
    elif not next_tid:
        run_type = "pull-in"
    elif overflow:
        run_type = "overflow"
    else:
        run_type = "in bay"
    total = int(last["Minute"] - first["Minute"] + 1)
    flag = (
        run_type == "in bay"
        and after_status == "DEPART"
        and SIT_FLAG_MIN_MINUTES <= total <= SIT_FLAG_MAX_MINUTES
    )
    # the stop the next trip actually departs from (its DEPART row), when the run ends in one
    if after_status == "DEPART" and after_stop:
        departure_stop = after_stop
    else:
        departure_stop = _txt(last.get("Stop ID"))
    return {
        "Block": block,
        "Type": run_type,
        "Flag": "YES" if flag else "",
        "Start": first["Timestamp"],
        "End": last["Timestamp"],
        "Total Minutes": total,
        "In-Bay Minutes": in_bay,
        "Overflow Minutes": overflow,
        "Arrival Stop": _txt(first.get("Stop ID")),
        "Departure Stop": departure_stop,
        "Arriving Trip": trip_lookup.get(prev_tid, ""),
        "Arriving Trip ID": prev_tid,
        "Departing Trip": trip_lookup.get(next_tid, ""),
        "Departing Trip ID": next_tid,
        "Ends With": after_status,
    }


def build_layover_runs(df_in: DataFrame) -> DataFrame:
    """List every stretch a block spends at the cluster between trips.

    A run is a maximal sequence of consecutive minutes for one block whose
    status is in ``SIT_STATUSES`` and whose stop is in the cluster. Runs are
    typed ``in bay`` (all minutes in a bay), ``overflow`` (some minutes on
    the overflow space), ``pull-out`` (no previous trip) or ``pull-in`` (no
    next trip). ``Flag`` marks in-bay runs ending in a departure whose length
    is between ``SIT_FLAG_MIN_MINUTES`` and ``SIT_FLAG_MAX_MINUTES``.

    Args:
    ----------
    df_in :
        Timeline rows for one cluster's blocks (all statuses, so the row
        after a run can be inspected). Needs ``ClusterName``.

    Returns:
    -------
    pandas.DataFrame
        One row per run.
    """
    df = df_in.copy()
    df["Minute"] = df["Timestamp"].apply(timestamp_to_minutes)
    df = df.dropna(subset=["Minute"]).sort_values(["Block", "Minute"])
    has_prev_next = "Prev Trip ID" in df.columns and "Next Trip ID" in df.columns

    # trip -> readable label, from rows that carry trip details
    trip_lookup: Dict[str, str] = {}
    for _, r in df[df["Trip ID"].notna() & (df["Trip ID"].astype(str) != "")].iterrows():
        tid = str(r["Trip ID"])
        if tid not in trip_lookup:
            route = str(r.get("Route Short Name") or r.get("Route") or "").strip()
            headsign = str(r.get("Trip Headsign") or "").strip()
            trip_lookup[tid] = f"{route} {headsign}".strip()

    occupying = bay_statuses()
    runs: List[Dict[str, Any]] = []
    for block, g in df.groupby("Block", sort=False):
        current: List[Dict[str, Any]] = []
        for r in g.to_dict("records"):
            in_cluster = pd.notna(r.get("ClusterName")) and r["Status"] in SIT_STATUSES
            if in_cluster and (not current or r["Minute"] == current[-1]["Minute"] + 1):
                current.append(r)
                continue
            if current:
                runs.append(
                    _layover_run_row(
                        block,
                        current,
                        str(r["Status"]),
                        _txt(r.get("Stop ID")),
                        trip_lookup,
                        has_prev_next,
                        occupying,
                    )
                )
                current = []
            if in_cluster:
                current.append(r)
        if current:
            runs.append(
                _layover_run_row(block, current, "END", "", trip_lookup, has_prev_next, occupying)
            )

    cols = [
        "Block",
        "Type",
        "Flag",
        "Start",
        "End",
        "Total Minutes",
        "In-Bay Minutes",
        "Overflow Minutes",
        "Arrival Stop",
        "Departure Stop",
        "Arriving Trip",
        "Arriving Trip ID",
        "Departing Trip",
        "Departing Trip ID",
        "Ends With",
    ]
    out = DataFrame(runs, columns=cols)
    return out.sort_values(["Start", "Block"]).reset_index(drop=True)


