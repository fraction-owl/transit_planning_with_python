"""Detect transit-cluster and stop-level scheduling conflicts.

The script analyzes block-level transit data to flag times when more
buses are scheduled than a bay or cluster can physically handle. It
reads the block-level XLSX outputs generated by
``scripts.gtfs_exports.block_status_timeline_exporter`` (Step 1) -- or the
combined CSV that step can write -- calculates capacity constraints from the
user-defined ``CLUSTER_DEFINITIONS``, and writes a detailed Excel workbook for
each cluster showing every event and highlighting any conflicts.

Two kinds of conflict are checked:

- *Stop* conflicts: more buses occupying one stop (bay) in a minute than its
  capacity. Which statuses count as occupying the bay is controlled by
  ``PASSENGER_SERVICE_STATUSES`` and ``COUNT_IN_BAY_LAYOVER_AT_STOP``.
- *Cluster* conflicts: more buses present anywhere in the cluster (bays plus
  overflow/layover spaces) than the cluster can hold.

Outputs
-------
- ``<Cluster_Name>_Conflicts.xlsx`` (one workbook per cluster, written to
  ``CLUSTER_CONFLICT_OUTPUT_FOLDER``):
  * “Summary” -- Step 1 assumptions (if found), per-stop conflict tallies,
    and minute counts under three rules: any stop in conflict; two or more
    stops in conflict at once (the “one bus can use the layover space” rule);
    and conflicts that remain once buses already on the overflow space are
    counted against it.
  * “Conflict Events” -- one row per run of consecutive conflict minutes at a
    stop, naming the buses involved.
  * “Overflow Events” -- runs of minutes where a layover/overflow space holds
    more buses than it can, per space when ``OVERFLOW_ROUTING`` is set.
  * “Layover Runs” -- every stretch a block spends at the cluster between
    trips (or before its first / after its last), with in-bay vs. overflow
    minutes and a flag for short in-bay sits before departure.
  * “AllStops” -- every minute-row in the cluster, conflict rows bold and
    shaded, plus one sheet per stop and overflow bay.

Typical usage
-------------
Update the paths in the CONFIGURATION section and run from a Jupyter
notebook, ArcGIS Pro’s “Python” pane, or directly from the command line.
"""

